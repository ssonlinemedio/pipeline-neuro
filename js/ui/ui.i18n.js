  // cientos/miles de nodos de una sola vez (dashboard, manual, tonos, etc.).
  const _translationQueue = [];
  let _queueScheduled = false;

  function _enqueueTranslation(node, lang, isAttribute) {
    _translationQueue.push({ node, lang, isAttribute: !!isAttribute });
    if (_queueScheduled) return;
    _queueScheduled = true;
    const schedule = window.requestIdleCallback
      ? cb => window.requestIdleCallback(cb, { timeout: 80 })
      : cb => setTimeout(() => cb({ timeRemaining: () => 8, didTimeout: true }), 0);
    schedule(_drainTranslationQueue);
  }

  function _drainTranslationQueue(deadline) {
    const start = performance.now();
    let processed = 0;
    while (_translationQueue.length) {
      const item = _translationQueue.shift();
      if (item && item.node && item.node.isConnected !== false) {
        if (item.isAttribute) translateElementAttributes(item.node, item.lang, true);
        else translateSubtree(item.node, item.lang);
      }
      processed++;
      // Límite doble: cantidad y tiempo real. Cede el control al navegador.
      if (processed >= 80 || performance.now() - start > 7 || (deadline && deadline.timeRemaining && deadline.timeRemaining() < 1)) break;
    }
    if (_translationQueue.length) {
      const schedule = window.requestIdleCallback
        ? cb => window.requestIdleCallback(cb, { timeout: 80 })
        : cb => setTimeout(() => cb({ timeRemaining: () => 8, didTimeout: true }), 0);
      schedule(_drainTranslationQueue);
    } else {
      _queueScheduled = false;
    }
  }

