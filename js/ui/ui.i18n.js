  function normalizeLang(lang) {
    const v = String(lang || '').toLowerCase();
    if (v.startsWith('zh')) return 'zh';
    if (v.startsWith('en')) return 'en';
    return 'es';
  }

  function getLang() {
    return normalizeLang(localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG);
  }

  function splitOuterWhitespace(text) {
    const m = String(text).match(/^(\s*)([\s\S]*?)(\s*)$/);
    return { pre:m ? m[1] : '', core:m ? m[2] : text, post:m ? m[3] : '' };
  }

  function translateText(text, lang) {
    lang = normalizeLang(lang || getLang());
    if (lang === 'es' || text == null) return String(text ?? '');
    const {pre, core, post} = splitOuterWhitespace(text);
    if (!core) return text;

    const dict = DICT[lang] || {};
    if (Object.prototype.hasOwnProperty.call(dict, core)) return pre + dict[core] + post;

    // Conserva emojis/iconos delante de una etiqueta UI conocida.
    const iconMatch = core.match(/^([\p{Extended_Pictographic}\uFE0F\u200D\s•·📊📚🀄🎵🎤⚙️🌌🌊⭐🏆🧠🔭]+)(.+)$/u);
    if (iconMatch) {
      const tail = iconMatch[2].trim();
      if (Object.prototype.hasOwnProperty.call(dict, tail)) {
        return pre + iconMatch[1] + dict[tail] + post;
      }
    }

    for (const [re, replacement] of (PATTERNS[lang] || [])) {
      if (re.test(core)) return pre + core.replace(re, replacement) + post;
    }
    return String(text);
  }

  function shouldSkip(el) {
    if (!el || el.nodeType !== 1) return false;
    return !!el.closest(SKIP_SELECTOR);
  }

  function translateTextNode(node, lang) {
    const parent = node.parentElement;
    if (!parent || shouldSkip(parent)) return;
    if (['SCRIPT','STYLE','TEXTAREA','OPTION'].includes(parent.tagName) && parent.tagName !== 'OPTION') return;
    const source = node.__i18nOriginal ?? node.nodeValue;
    if (node.__i18nOriginal == null) node.__i18nOriginal = source;
    const out = translateText(source, lang);
    if (node.nodeValue !== out) node.nodeValue = out;
  }

  // Evita ciclos del MutationObserver: recordamos exactamente qué valor escribió i18n.
  const _lastAppliedAttrs = new WeakMap();

  function translateElementAttributes(el, lang, fromObserver) {
    if (!el || el.nodeType !== 1 || shouldSkip(el)) return;
    const attrs = ['placeholder','title','aria-label'];
    let state = _lastAppliedAttrs.get(el);
    if (!state) { state = Object.create(null); _lastAppliedAttrs.set(el, state); }

    attrs.forEach(attr => {
      if (!el.hasAttribute(attr)) return;
      const current = el.getAttribute(attr);
      const prop = '__i18n_' + attr;

      // Si el callback viene del observer y coincide con lo último que escribió i18n,
      // es una mutación propia: no volver a procesarla.
      if (fromObserver && state[attr] === current) return;

      // Si otro módulo cambió el atributo, ese nuevo valor pasa a ser la fuente original.
      if (fromObserver && state[attr] !== current) el[prop] = current;
      const source = el[prop] ?? current;
      if (el[prop] == null) el[prop] = source;
      const out = translateText(source, lang);

      // setAttribute incluso con el mismo valor puede generar mutaciones en algunos navegadores.
      // Solo escribimos cuando realmente cambia.
      if (current !== out) {
        state[attr] = out;
        el.setAttribute(attr, out);
      } else {
        state[attr] = current;
      }
    });
  }

  function translateSubtree(root, lang) {
    lang = normalizeLang(lang || getLang());
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) return translateTextNode(root, lang);
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;
    if (root.nodeType === Node.ELEMENT_NODE) translateElementAttributes(root, lang);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let n;
    while ((n = walker.nextNode())) {
      if (n.nodeType === Node.TEXT_NODE) translateTextNode(n, lang);
      else translateElementAttributes(n, lang);
    }
  }


  // Traduce un fragmento HTML generado por los módulos UI antes de insertarlo.
  // Solo modifica nodos visuales conocidos; respeta SKIP_SELECTOR para contenido pedagógico.
  function translateHtml(html, lang) {
    if (html == null) return '';
    lang = normalizeLang(lang || getLang());
    if (lang === 'es') return String(html);
    const template = document.createElement('template');
    template.innerHTML = String(html);
    const walker = document.createTreeWalker(template.content, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let n;
    while ((n = walker.nextNode())) {
      if (n.nodeType === Node.TEXT_NODE) {
        const parent = n.parentElement;
        if (!parent || shouldSkip(parent) || ['SCRIPT','STYLE','TEXTAREA'].includes(parent.tagName)) continue;
        n.nodeValue = translateText(n.nodeValue, lang);
      } else if (n.nodeType === Node.ELEMENT_NODE) {
        translateElementAttributes(n, lang);
      }
    }
    return template.innerHTML;
  }


  // Traducción para mensajes de UI (alert/confirm/prompt) que suelen ser multilínea.
  // Se usa SOLO en diálogos de interfaz; no se aplica a textarea/prompts pedagógicos.
  function translateMessage(text, lang) {
    lang = normalizeLang(lang || getLang());
    if (lang === 'es' || text == null) return String(text ?? '');
    const dict = DICT[lang] || {};
    const keys = Object.keys(dict).filter(k => k.length >= 4).sort((a,b) => b.length - a.length);
    return String(text).split('\n').map(line => {
      let out = translateText(line, lang);
      if (out !== line) return out;
      // Traduce fragmentos de UI conocidos preservando valores dinámicos (idioma, nivel, cifras, modelos...).
      let work = line;
      for (const k of keys) {
        if (work.includes(k)) work = work.split(k).join(dict[k]);
      }
      return work;
    }).join('\n');
  }

  function refresh(lang) {
    lang = normalizeLang(lang || getLang());
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
    translateSubtree(document.body, lang);
    document.querySelectorAll('[data-ui-lang-select]').forEach(s => { if (s.value !== lang) s.value = lang; });
  }

  function setLang(lang) {
    lang = normalizeLang(lang);
    localStorage.setItem(STORAGE_KEY, lang);
    refresh(lang);
    window.dispatchEvent(new CustomEvent('pipeline:uiLanguageChanged', { detail:{ language:lang } }));
  }

